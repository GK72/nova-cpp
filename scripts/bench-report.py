#!/usr/bin/env python3
"""Turn Google Benchmark JSON results into AsciiDoc tables.

Reads `doc/bench/bench-<module>.json` (written by `ci/bench.sh`) and writes
`doc/bench/results-<module>.adoc`, which the module's page includes. The
results must come from repeated runs: the tables show the median, the standard
deviation and the coefficient of variation (CV = std dev / mean) of the
repetitions, all of the CPU time per call in one thread. The rate counts all
threads: bytes per second as the benchmark reports it, or calls per second
from the wall-clock time.

A benchmark name is split into a family and an instance: the trailing parts
that are numbers or `key:value` pairs (`crc32/pclmul/bytes:4096`, `log/threads:2`)
are the instance, the rest is the family. Each family gets a table.

Usage:
    scripts/bench-report.py                 # every doc/bench/bench-*.json
    scripts/bench-report.py checksum log    # the given modules
"""

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent.parent / "doc" / "bench"

NS_PER_UNIT = {"ns": 1.0, "us": 1e3, "ms": 1e6, "s": 1e9}
INSTANCE_PART = re.compile(r"^(\d+|[a-z_]+:[\w.]+)$")


def split_name(run_name: str) -> tuple[str, str]:
    """Split `family/arg/...` into the family and the instance."""
    parts = run_name.split("/")
    cut = len(parts)
    while cut > 1 and INSTANCE_PART.match(parts[cut - 1]):
        cut -= 1
    return "/".join(parts[:cut]), "/".join(parts[cut:])


def format_time(ns: float) -> str:
    for unit, scale in (("s", 1e9), ("ms", 1e6), ("µs", 1e3)):
        if ns >= scale:
            return f"{ns / scale:.3g} {unit}"
    return f"{ns:.3g} ns"


def format_bytes(size: int) -> str:
    for unit, scale in (("MiB", 1 << 20), ("KiB", 1 << 10)):
        if size >= scale and size % scale == 0:
            return f"{size // scale} {unit}"
    return f"{size} B"


def format_part(part: str) -> str:
    """`bytes:N` is a size, another `key:value` reads as `value key`, a bare number as is."""
    if ":" not in part:
        return part
    key, value = part.split(":", 1)
    return format_bytes(int(value)) if key == "bytes" else f"{value} {key}"


def format_instance(instance: str) -> str:
    return ", ".join(format_part(part) for part in instance.split("/")) if instance else "-"


def format_rate(stats: dict) -> str:
    median = stats["median"]
    if "bytes_per_second" in median:
        rate = median["bytes_per_second"]
        if rate >= 1 << 30:
            return f"{rate / (1 << 30):.3g} GiB/s"
        return f"{rate / (1 << 20):.3g} MiB/s"
    ns = median["real_time"] * NS_PER_UNIT[median["time_unit"]]
    ops = 1e9 / ns
    for unit, scale in (("G", 1e9), ("M", 1e6), ("k", 1e3)):
        if ops >= scale:
            return f"{ops / scale:.3g}{unit} ops/s"
    return f"{ops:.3g} ops/s"


def collect(benchmarks: list[dict]) -> dict[str, dict[str, dict]]:
    """Group the aggregates as family -> instance -> aggregate -> entry."""
    families: dict[str, dict[str, dict]] = defaultdict(lambda: defaultdict(dict))
    for entry in benchmarks:
        if entry.get("run_type") != "aggregate":
            continue
        family, instance = split_name(entry["run_name"])
        families[family][instance][entry["aggregate_name"]] = entry
    return families


def table(family: str, instances: dict[str, dict]) -> list[str]:
    lines = [
        f".{family}",
        '[cols="1,1,1,1,1",options="header"]',
        "|===",
        "| Instance | Median time | Std dev | CV | Median rate",
        "",
    ]
    for instance, stats in instances.items():
        missing = {"median", "stddev", "cv"} - stats.keys()
        if missing:
            sys.exit(f"{family}/{instance}: no {', '.join(sorted(missing))}; run with repetitions")
        median, stddev = stats["median"], stats["stddev"]
        scale = NS_PER_UNIT[median["time_unit"]]
        cv = stats["cv"]["cpu_time"]
        lines.append(
            f"| {format_instance(instance)}"
            f" | {format_time(median['cpu_time'] * scale)}"
            f" | {format_time(stddev['cpu_time'] * scale)}"
            f" | {cv * 100:.1f}%"
            f" | {format_rate(stats)}"
        )
    lines += ["|===", ""]
    return lines


def report(module: str, results: dict) -> str:
    context = results["context"]
    benchmarks = results["benchmarks"]
    repetitions = next((b["repetitions"] for b in benchmarks if "repetitions" in b), 1)
    load = ", ".join(f"{value:.2f}" for value in context.get("load_avg", []))

    lines = [
        f"// Generated by scripts/bench-report.py from bench-{module}.json. Do not edit.",
        "",
        f"Measured {context['date'][:10]} on `{context['host_name']}`,"
        f" {repetitions} repetitions, load average {load}."
        f" Times are CPU time per call in one thread; the rate counts all threads,"
        f" from wall-clock time.",
        "",
    ]
    for family, instances in collect(benchmarks).items():
        lines += table(family, instances)
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("modules", nargs="*", help="modules to report (default: all)")
    args = parser.parse_args()

    modules = args.modules or sorted(p.stem.removeprefix("bench-") for p in BENCH_DIR.glob("bench-*.json"))
    for module in modules:
        source = BENCH_DIR / f"bench-{module}.json"
        target = BENCH_DIR / f"results-{module}.adoc"
        target.write_text(report(module, json.loads(source.read_text())))
        print(f"{source.name} -> {target.name}")


if __name__ == "__main__":
    main()
